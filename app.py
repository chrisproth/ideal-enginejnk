# ---------------- BLACKJACK ----------------
def hand_value(hand):
    total = sum(VALUES[r] for r, s in hand)
    aces = sum(r == "A" for r, s in hand)
    while total > 21 and aces:
        total -= 10
        aces -= 1
    return total


def natural(hand):
    return len(hand) == 2 and hand_value(hand) == 21


def card_color(suit):
    return "red" if suit in ("♥", "♦") else "black"


def perfect_pairs_result(hand):
    a, b = hand[:2]
    if a[0] != b[0]:
        return None, 0
    if a[1] == b[1]:
        return "Perfect Pair", 25
    if card_color(a[1]) == card_color(b[1]):
        return "Colored Pair", 12
    return "Mixed Pair", 6


def three_card_straight(ranks):
    vals = sorted(set(RANK_VALUE[r] for r in ranks))
    if len(vals) != 3:
        return False
    if vals == [2, 3, 14]:
        return True
    return vals[2] - vals[0] == 2 and vals[1] - vals[0] == 1


def twentyone3_result(cards):
    ranks = [c[0] for c in cards]
    suits = [c[1] for c in cards]
    same_rank = len(set(ranks)) == 1
    flush = len(set(suits)) == 1
    straight = three_card_straight(ranks)
    exact_same = len(set(cards)) == 1
    if same_rank and exact_same:
        return "Suited Trips", 100
    if straight and flush:
        return "Straight Flush", 40
    if same_rank:
        return "Three of a Kind", 25
    if straight:
        return "Straight", 10
    if flush:
        return "Flush", 5
    return None, 0


def blackjack_view(g, reveal=False):
    return {
        "player_hand": card_list(g["player"]),
        "dealer_hand": card_list(g["dealer"]) if reveal else [card_list(g["dealer"])[0], {"rank": "?", "suit": "?"}],
        "player_value": hand_value(g["player"]),
        "dealer_value": hand_value(g["dealer"]) if reveal else None,
        "bet": g["bet"],
        "status": g["status"],
        "can_double": g["status"] == "playing" and len(g["player"]) == 2,
        "side_results": g.get("side_results", []),
    }


def finish_blackjack(player, g):
    while hand_value(g["dealer"]) < 17:
        g["dealer"].append(g["deck"].pop())
    pv, dv, bet = hand_value(g["player"]), hand_value(g["dealer"]), g["bet"]
    if pv > 21:
        g["status"] = "bust"
    elif dv > 21 or pv > dv:
        adjust_balance(player["id"], bet * 2, "blackjack", "Blackjack win")
        g["status"] = "win"
    elif pv == dv:
        adjust_balance(player["id"], bet, "blackjack", "Blackjack push")
        g["status"] = "push"
    else:
        g["status"] = "lose"
    return blackjack_view(g, True)


# ---------------- ROULETTE ----------------
def wheel_color(n):
    return "green" if n == 0 else "red" if n in REDS else "black"


def roulette_win(t, v, n):
    if t in ("red", "black"): return wheel_color(n) == t, 1
    if t == "green": return n == 0, 35
    if t == "number": return n == int(v), 35
    if t == "odd": return n != 0 and n % 2 == 1, 1
    if t == "even": return n != 0 and n % 2 == 0, 1
    if t == "low": return 1 <= n <= 18, 1
    if t == "high": return 19 <= n <= 36, 1
    if t == "1st12": return 1 <= n <= 12, 2
    if t == "2nd12": return 13 <= n <= 24, 2
    if t == "3rd12": return 25 <= n <= 36, 2
    if t == "col1": return n != 0 and n % 3 == 1, 2
    if t == "col2": return n != 0 and n % 3 == 2, 2
    if t == "col3": return n != 0 and n % 3 == 0, 2
    if t == "basket": return n in {0, 1, 2, 3}, 8
    if t == "snake": return n in SNAKE_NUMBERS, 2
    return False, 0



def adjust_balance(pid, amount, game, description):
    amount = int(amount)
    with engine.begin() as c:
        p = c.execute(text("SELECT balance FROM players WHERE id=:id"), {"id": pid}).mappings().first()
        if not p:
            raise ValueError("Player not found.")
        new_balance = int(p["balance"]) + amount
        if new_balance < 0:
            raise ValueError("Insufficient balance.")
        c.execute(text("UPDATE players SET balance=:balance WHERE id=:id"), {"balance": new_balance, "id": pid})
        c.execute(text("""INSERT INTO transactions(player_id,game,amount,balance_after,description)
                          VALUES(:player_id,:game,:amount,:balance_after,:description)"""), {
            "player_id": pid,
            "game": game,
            "amount": amount,
            "balance_after": new_balance,
            "description": description,
        })
        return new_balance


def charge_wagers(pid, game, wagers):
    clean = []
    for description, amount in wagers:
        amount = int(amount or 0)
        if amount < 0:
            raise ValueError("Wagers cannot be negative.")
        if amount:
            clean.append((description, amount))
    total = sum(a for _, a in clean)
    if total <= 0:
        return current()["balance"]

    with engine.begin() as c:
        p = c.execute(text("SELECT balance FROM players WHERE id=:id"), {"id": pid}).mappings().first()
        if not p:
            raise ValueError("Player not found.")
        running = int(p["balance"])
        if total > running:
            raise ValueError("Insufficient balance for all selected wagers.")
        for description, amount in clean:
            running -= amount
            c.execute(text("""INSERT INTO transactions(player_id,game,amount,balance_after,description)
                              VALUES(:player_id,:game,:amount,:balance_after,:description)"""), {
                "player_id": pid, "game": game, "amount": -amount,
                "balance_after": running, "description": description,
            })
        c.execute(text("UPDATE players SET balance=:balance WHERE id=:id"), {"balance": running, "id": pid})
        return running


def credit_wager(pid, stake, odds_to_one, game, description):
    if not stake:
        return 0
    returned = int(stake * (odds_to_one + 1))
    adjust_balance(pid, returned, game, description)
    return returned



def straight_high(values):
    vals = sorted(set(values), reverse=True)
    if 14 in vals:
        vals.append(1)
    for high in range(14, 4, -1):
        seq = set(range(high - 4, high + 1))
        if seq.issubset(set(vals)):
            return high
    return 0


def standard_poker_eval(cards):
    ranks = [c[0] for c in cards]
    vals = [RANK_VALUE[r] for r in ranks]
    suits = [c[1] for c in cards]
    counts = Counter(vals)
    ordered_counts = sorted(((cnt, val) for val, cnt in counts.items()), reverse=True)
    flush = len(set(suits)) == 1
    sh = straight_high(vals)

    if len(counts) == 1:
        return (10, (max(vals),), "Five of a Kind")
    if flush and sh == 14 and {10,11,12,13,14}.issubset(set(vals)):
        return (9, (14,), "Royal Flush")
    if flush and sh:
        return (8, (sh,), "Straight Flush")
    if 4 in counts.values():
        four = max(v for v,c in counts.items() if c == 4)
        kicker = max(v for v,c in counts.items() if c != 4)
        return (7, (four, kicker), "Four of a Kind")
    if sorted(counts.values()) == [2,3]:
        trip = max(v for v,c in counts.items() if c == 3)
        pair = max(v for v,c in counts.items() if c == 2)
        return (6, (trip, pair), "Full House")
    if flush:
        return (5, tuple(sorted(vals, reverse=True)), "Flush")
    if sh:
        return (4, (sh,), "Straight")
    if 3 in counts.values():
        trip = max(v for v,c in counts.items() if c == 3)
        kicks = sorted((v for v,c in counts.items() if c == 1), reverse=True)
        return (3, (trip, *kicks), "Three of a Kind")
    pairs = sorted((v for v,c in counts.items() if c == 2), reverse=True)
    if len(pairs) >= 2:
        kicker = max(v for v,c in counts.items() if c == 1)
        return (2, (pairs[0], pairs[1], kicker), "Two Pair")
    if len(pairs) == 1:
        kicks = sorted((v for v,c in counts.items() if c == 1), reverse=True)
        return (1, (pairs[0], *kicks), "Pair")
    return (0, tuple(sorted(vals, reverse=True)), "High Card")


WILD_CANDIDATES = tuple((r, s) for s in SUITS for r in RANKS)


@lru_cache(maxsize=4096)
def dj_eval_cached(canonical):
    cards = [tuple(x.split("|", 1)) for x in canonical]
    wild_count = sum(r in ("2", "JOKER") for r, s in cards)
    if wild_count == 5:
        return (11, (14,), "Five Wilds")
    naturals = [c for c in cards if c[0] not in ("2", "JOKER")]
    if wild_count == 0:
        return standard_poker_eval(cards)
    best = (-1, (), "")
    for subs in itertools.combinations_with_replacement(WILD_CANDIDATES, wild_count):
        ev = standard_poker_eval(naturals + list(subs))
        if (ev[0], ev[1]) > (best[0], best[1]):
            best = ev
    return best


def dj_eval(cards):
    canonical = tuple(sorted(f"{r}|{s}" for r,s in cards))
    return dj_eval_cached(canonical)


def dj_natural(cards, best_eval):
    if any(r == "JOKER" for r,s in cards):
        return False
    standard = standard_poker_eval(cards)
    return standard[:2] == best_eval[:2]


